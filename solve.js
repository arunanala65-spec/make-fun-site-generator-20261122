// A faster drop-in for makefun-site 1.0.0, written from scratch from its README spec.
// Same answers byte for byte, less CPU: bulk escaping, cached slugs, a fused
// Markdown lexer+renderer, indexOf-based inline scanning and array-joined templates.

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/g;
// Faster than replace-with-callback: one regex scan, string building only past the
// first special character; a string with no special character is returned as-is.
// Never re-entered (it calls no user code), so the shared regex is safe.
function escapeHtml(t) {
  let out = '';
  let last = 0;
  ESC_RE.lastIndex = 0;
  let m;
  while ((m = ESC_RE.exec(t)) !== null) {
    out += t.slice(last, m.index) + ESCAPES[m[0]];
    last = m.index + 1;
  }
  if (last === 0) return t;
  return out + t.slice(last);
}

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const dirOf = (path) => (path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '');
const RESERVED = ['posts', 'tags', 'page'];

