const ESCAPABLE = new Uint8Array(128);
for (const c of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE[c.charCodeAt(0)] = 1;
function isEscapableCode(code) {
  return code < 128 && ESCAPABLE[code] === 1;
}

// True when the character at j is escaped: an odd run of backslashes just before it.
function escapedBefore(s, j) {
  let k = 0;
  while (j - 1 - k >= 0 && s[j - 1 - k] === '\\') k++;
  return (k & 1) === 1;
}

// The next index at or after `from` holding one of \ ` * [, or -1.
// indexOf runs in C++; this jumps over plain runs instead of walking them char by char.
function nextSpecial(s, from) {
  const a = s.indexOf('\\', from);
  const b = s.indexOf('`', from);
  const c = s.indexOf('*', from);
  const d = s.indexOf('[', from);
  let j = -1;
  if (a !== -1) j = a;
  if (b !== -1 && (j === -1 || b < j)) j = b;
  if (c !== -1 && (j === -1 || c < j)) j = c;
  if (d !== -1 && (j === -1 || d < j)) j = d;
  return j;
}

function inline(s, link) {
  let out = '';
  let i = 0; // start of the current plain run
  let pos = 0; // where the next special-character search starts
  const n = s.length;
  while (pos < n) {
    const j = nextSpecial(s, pos);
    if (j === -1) break;
    const c = s[j];
    if (c === '\\') {
      if (j + 1 < n && isEscapableCode(s.charCodeAt(j + 1))) {
        if (j > i) out += escapeHtml(s.slice(i, j));
        out += s[j + 1];
        i = j + 2;
        pos = j + 2;
      } else {
        pos = j + 1;
      }
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        if (j > i) out += escapeHtml(s.slice(i, j));
        out += '<code>' + escapeHtml(s.slice(j + 1, k)) + '</code>';
        i = k + 1;
        pos = k + 1;
      } else {
        pos = j + 1;
      }
      continue;
    }
    if (c === '*') {
      if (escapedBefore(s, j)) {
        pos = j + 1;
        continue;
      }
      if (s[j + 1] === '*') {
        let k = s.indexOf('**', j + 2);
        while (k !== -1 && escapedBefore(s, k)) k = s.indexOf('**', k + 1);
        if (k > j + 2) {
          if (j > i) out += escapeHtml(s.slice(i, j));
          out += '<strong>' + inline(s.slice(j + 2, k), link) + '</strong>';
          i = k + 2;
          pos = k + 2;
        } else {
          pos = j + 2;
        }
        continue;
      }
      let k = s.indexOf('*', j + 1);
      while (k !== -1) {
        if (escapedBefore(s, k)) {
          k = s.indexOf('*', k + 1);
          continue;
        }
        if (s[k + 1] === '*') {
          k = s.indexOf('*', k + 2);
          continue;
        }
        break;
      }
      if (k > j + 1) {
        if (j > i) out += escapeHtml(s.slice(i, j));
        out += '<em>' + inline(s.slice(j + 1, k), link) + '</em>';
        i = k + 1;
        pos = k + 1;
      } else {
        pos = j + 1;
      }
      continue;
    }
    // '['
    if (escapedBefore(s, j)) {
      pos = j + 1;
      continue;
    }
    let k = s.indexOf(']', j + 1);
    while (k !== -1 && escapedBefore(s, k)) k = s.indexOf(']', k + 1);
    let m = -1;
    let target = '';
    if (k !== -1 && s[k + 1] === '(') {
      m = s.indexOf(')', k + 2);
      if (m !== -1) target = s.slice(k + 2, m);
    }
    if (m !== -1 && target !== '' && !/\s/.test(target)) {
      if (j > i) out += escapeHtml(s.slice(i, j));
      out += '<a href="' + escapeHtml(link(target)) + '">' + inline(s.slice(j + 1, k), link) + '</a>';
      i = m + 1;
      pos = m + 1;
      continue;
    }
    pos = j + 1;
  }
  if (n > i) out += escapeHtml(s.slice(i, n));
  return out;
}

function isLangChar(c) {
  return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-';
}

function fenceOpen(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let j = 3;
  while (j < line.length && isLangChar(line[j])) j++;
  for (let k = j; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return null;
  }
  return line.slice(3, j);
}

function fenceClose(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let k = 3; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return false;
  }
  return true;
}

function headingOf(line) {
  let h = 0;
  while (h < line.length && line[h] === '#') h++;
  if (h === 0 || h > 6) return null;
  if (line[h] !== ' ' && line[h] !== '\t') return null;
  let s = h;
  while (s < line.length && (line[s] === ' ' || line[s] === '\t')) s++;
  let e = line.length;
  while (e > s && (line[e - 1] === ' ' || line[e - 1] === '\t')) e--;
  if (e === s) return null;
  return { depth: h, text: line.slice(s, e) };
}

function isHr(line) {
  const t = line[0] === '-' ? '---' : line[0] === '*' ? '***' : null;
  if (t === null || !line.startsWith(t)) return false;
  for (let k = 3; k < line.length; k++) {
    if (line[k] !== ' ' && line[k] !== '\t') return false;
  }
  return true;
}

function bulletOf(line) {
  if ((line[0] === '-' || line[0] === '*') && line[1] === ' ') return { text: line.slice(2) };
  return null;
}

function orderedOf(line) {
  let j = 0;
  while (j < line.length && line[j] >= '0' && line[j] <= '9') j++;
  if (j === 0 || j > 9) return null;
  if (line[j] !== '.' || line[j + 1] !== ' ') return null;
  return { start: Number(line.slice(0, j)), text: line.slice(j + 2) };
}

function isContinued(line) {
  if (line[0] !== ' ' || line[1] !== ' ') return false;
  let j = 2;
  while (j < line.length && line[j] === ' ') j++;
  if (j >= line.length) return false;
  return !/\s/.test(line[j]);
}

function paraEnd(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

function renderMarkdown(lines, link, slugify) {
  let html = '';
  const toc = [];
  let excerpt = null;
  const ids = new Set();
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const fence = fenceOpen(line);
    if (fence !== null) {
      const body = [];
      i++;
      while (i < n && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = fence === '' ? '' : ` class="language-${escapeHtml(fence)}"`;
      html += `<pre><code${cls}>${body.length ? escapeHtml(body.join('\n')) + '\n' : ''}</code></pre>\n`;
      continue;
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugify(hd.text), ids);
      const h = inline(hd.text, link);
      html += `<h${hd.depth} id="${id}">${h}</h${hd.depth}>\n`;
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html: h });
      i++;
      continue;
    }
    if (isHr(line)) {
      html += '<hr>\n';
      i++;
      continue;
    }
    if (line[0] === '>') {
      const body = [];
      while (i < n && lines[i][0] === '>') {
        let s = lines[i].slice(1);
        if (s[0] === ' ') s = s.slice(1);
        body.push(s);
        i++;
      }
      const inner = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') inner.push(t);
      }
      html += inner.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(inner.join('\n'), link)}</p>\n</blockquote>\n`;
      continue;
    }
    const bl = bulletOf(line);
    const ol = bl === null ? orderedOf(line) : null;
    if (bl !== null || ol !== null) {
      const isOrdered = ol !== null;
      const start = isOrdered ? ol.start : 1;
      const items = [];
      while (i < n) {
        const l = lines[i];
        if (isOrdered) {
          const m = orderedOf(l);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
            continue;
          }
        } else {
          const m = bulletOf(l);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
            continue;
          }
        }
        if (isContinued(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
          continue;
        }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      html += `${open}\n`;
      for (const it of items) html += `<li>${inline(it.join('\n'), link)}</li>\n`;
      html += `</${tag}>\n`;
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !paraEnd(lines[i])) body.push(trimLine(lines[i++]));
    const h = inline(body.join('\n'), link);
    if (excerpt === null) excerpt = h;
    html += `<p>${h}</p>\n`;
  }
  return { html, toc, excerpt: excerpt ?? '' };
}

